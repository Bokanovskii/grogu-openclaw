import { open } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { withFileLock } from "../../src/infra/file-lock.js";
import { FsSafeError, pathExists, root } from "../../src/infra/fs-safe.js";
import { writeJsonAtomic } from "../../src/infra/json-files.js";
import { measureStorageLimits } from "./capacity.js";
import {
  parseDeploySettings,
  parseRuntimeSettings,
  protectedMaxFileBytes,
  protectedOpenClawConfig,
  readSettingsJson,
  sparkyRef,
  subjectPattern,
  testClientIdPattern,
} from "./settings.js";
import {
  provisionProtectedStorageKeyAndMigrate,
  requireProtectedStorageEncryption,
  resolveProtectedStorageKeyFile,
} from "./storage-key.js";
import { protectedTurnExtras, protectedTurnMarks } from "./turn-timing.js";

class MaintenanceRefused extends Error {}

// Older releases seeded onboarding into the shared workspace; skipBootstrap no
// longer creates it. Retire only those generated bytes, never an edit or a link.
async function retireGeneratedBootstrap(workspaceDir: string, assertCurrent: () => void) {
  if (!(await pathExists(workspaceDir))) {
    return false;
  }
  const { DEFAULT_BOOTSTRAP_FILENAME, isGeneratedTemplateContent } =
    await import("../../src/agents/workspace.js");
  const { MAX_WORKSPACE_BOOTSTRAP_FILE_BYTES } =
    await import("../../src/agents/workspace-bootstrap-read.js");
  const workspace = await root(workspaceDir, {
    hardlinks: "reject",
    maxBytes: MAX_WORKSPACE_BOOTSTRAP_FILE_BYTES,
    symlinks: "reject",
  });
  const kept = new MaintenanceRefused(
    "Workspace BOOTSTRAP.md is not the generated default; it was kept.",
  );
  let content: string;
  try {
    if (!(await workspace.exists(DEFAULT_BOOTSTRAP_FILENAME))) {
      return false;
    }
    content = (await workspace.readBytes(DEFAULT_BOOTSTRAP_FILENAME)).toString("utf8");
  } catch (error) {
    throw error instanceof FsSafeError ? kept : error;
  }
  if (!(await isGeneratedTemplateContent(DEFAULT_BOOTSTRAP_FILENAME, content))) {
    throw kept;
  }
  await workspace.remove(DEFAULT_BOOTSTRAP_FILENAME, { assertBeforeMutation: assertCurrent });
  return true;
}

async function main() {
  const [action, arg, ...rest] = process.argv.slice(2);
  const stateDir = process.env.OPENCLAW_STATE_DIR;
  const configPath = process.env.OPENCLAW_CONFIG_PATH;
  const home = process.env.HOME;
  if (
    !home ||
    !path.isAbsolute(home) ||
    stateDir !== path.join(home, "state") ||
    configPath !== path.join(home, "config", "openclaw.json") ||
    process.getuid?.() === 0
  ) {
    throw new Error("Maintenance requires the isolated service account and environment.");
  }
  resolveProtectedStorageKeyFile();
  const configDir = path.dirname(configPath);
  const runtimePath = path.join(configDir, "protected.json");
  if (action === "turn-timings" && arg === undefined && rest.length === 0) {
    const file = await open(path.join(stateDir, "logs", "runtime.stdout.log"), "r");
    try {
      const size = (await file.stat()).size;
      const length = Math.min(size, 1024 * 1024);
      const bytes = Buffer.alloc(length);
      const { bytesRead } = await file.read(bytes, 0, length, size - length);
      const lines = bytes.subarray(0, bytesRead).toString("utf8").split("\n");
      if (size > length) {
        lines.shift();
      }
      lines.pop();
      const fields = [
        "admissionMs",
        "providerRequestStartMs",
        "firstProviderOutputMs",
        "firstClientVisibleOutputMs",
        "accessChecks",
        "accessValidationMs",
        "completionMs",
      ] as const;
      const isElapsed = (value: unknown): value is number =>
        typeof value === "number" && Number.isFinite(value) && value >= 0;
      // Only fixed names and numbers are printed; any other field in the log is dropped.
      const knownMarks = new Set<string>(protectedTurnMarks);
      const outcomes = new Set<unknown>(["complete", "failed", "interrupted"]);
      const records: string[] = [];
      for (const line of lines) {
        const prefix = "[protected-turn-timing] ";
        if (!line.startsWith(prefix)) {
          continue;
        }
        let value: unknown;
        try {
          value = JSON.parse(line.slice(prefix.length));
        } catch (error) {
          if (error instanceof SyntaxError) {
            continue;
          }
          throw error;
        }
        if (!value || typeof value !== "object") {
          continue;
        }
        const record = value as Record<string, unknown>;
        if (!fields.every((field) => record[field] === null || isElapsed(record[field]))) {
          continue;
        }
        const printed: Record<string, unknown> = Object.fromEntries(
          fields.map((field) => [field, record[field]]),
        );
        if (outcomes.has(record.outcome)) {
          printed.outcome = record.outcome;
        }
        for (const extra of protectedTurnExtras) {
          if (isElapsed(record[extra])) {
            printed[extra] = record[extra];
          }
        }
        if (record.marks && typeof record.marks === "object") {
          const marks = Object.entries(record.marks).filter(
            ([name, elapsed]) => knownMarks.has(name) && isElapsed(elapsed),
          );
          if (marks.length > 0) {
            printed.marks = Object.fromEntries(marks);
          }
        }
        records.push(JSON.stringify(printed));
      }
      if (records.length > 0) {
        process.stdout.write(`${records.slice(-20).join("\n")}\n`);
      }
    } finally {
      await file.close();
    }
    return;
  }
  if (
    action === "init" &&
    arg === "--deploy-json" &&
    rest.length === 1 &&
    path.isAbsolute(rest[0]!)
  ) {
    const storageEncryption = requireProtectedStorageEncryption();
    storageEncryption.dispose();
    const deploy = parseDeploySettings(await readSettingsJson(rest[0]!));
    const storageLimits = measureStorageLimits(stateDir);
    const configRoot = await root(configDir);
    // Install each file once; never silently replace an existing allowlist.
    const config = protectedOpenClawConfig(
      stateDir,
      fileURLToPath(new URL("../..", import.meta.url)),
    );
    const provider = config.models?.providers?.sparky;
    if (!provider) {
      throw new Error("Missing isolated Sparky configuration.");
    }
    provider.apiKey = sparkyRef;
    await configRoot.create("openclaw.json", `${JSON.stringify(config, null, 2)}\n`, {
      private: true,
      atomic: true,
    });
    await configRoot.create(
      "protected.json",
      `${JSON.stringify(
        {
          ...deploy,
          stateDir,
          allowedSubjects: [],
          sparkySecret: sparkyRef,
          storageLimits,
        },
        null,
        2,
      )}\n`,
      { private: true, atomic: true },
    );
    process.stdout.write("Initialized Alcove config with no admitted subjects.\n");
    return;
  }
  if (action === "provision-storage-key" && arg === undefined && rest.length === 0) {
    const { configureProtectedRuntimeWorkers } = await import("./runtime-workers.js");
    await configureProtectedRuntimeWorkers(fileURLToPath(new URL("../..", import.meta.url)));
    const { acquireProtectedStateOwner } = await import("./state-owner.js");
    const owner = await acquireProtectedStateOwner(stateDir);
    if (!owner) {
      throw new MaintenanceRefused("Stop the listener before provisioning protected storage.");
    }
    try {
      owner.assertCurrent();
      try {
        await provisionProtectedStorageKeyAndMigrate(() => owner.assertCurrent());
      } catch (error) {
        if (error instanceof Error) {
          throw new MaintenanceRefused(error.message);
        }
        throw new MaintenanceRefused(
          "Protected storage provisioning failed; keep the listener stopped and preserve the original key.",
        );
      }
    } finally {
      owner.release();
    }
    process.stdout.write(
      "Protected storage key is ready; shared state, the agent store, and user files are encrypted.\n",
    );
    return;
  }
  const updateSettings = (
    change: (settings: ReturnType<typeof parseRuntimeSettings>) => object | undefined,
  ) =>
    withFileLock(
      runtimePath,
      {
        retries: { retries: 5, factor: 2, minTimeout: 25, maxTimeout: 300 },
        stale: 10_000,
        staleRecovery: "remove-if-definitely-stale",
      },
      async () => {
        const settings = parseRuntimeSettings(await readSettingsJson(runtimePath));
        if (settings.stateDir !== stateDir) {
          throw new Error("Alcove config state directory mismatch.");
        }
        const next = change(settings);
        if (next) {
          await writeJsonAtomic(runtimePath, next, { mode: 0o600, durable: true });
        }
      },
    );
  if (action === "add-subject" && arg && subjectPattern.test(arg) && rest.length === 0) {
    const subject = arg.toLowerCase();
    const settings = parseRuntimeSettings(await readSettingsJson(runtimePath));
    if (settings.stateDir !== stateDir) {
      throw new Error("Alcove config state directory mismatch.");
    }
    const { acquireProtectedStateOwner } = await import("./state-owner.js");
    const owner = await acquireProtectedStateOwner(stateDir);
    if (!owner) {
      throw new MaintenanceRefused("Stop the listener before adding a subject.");
    }
    try {
      const { addProtectedSubject } = await import("./admission-store.js");
      owner.assertCurrent();
      const result = await addProtectedSubject(stateDir, {
        issuer: settings.accessIssuer,
        subject,
      });
      if (result === "removed") {
        throw new Error("A removed subject cannot be restored by this command.");
      }
    } finally {
      owner.release();
    }
    process.stdout.write("Alcove admission is recorded; restart the listener to apply it.\n");
    return;
  }
  if (
    action === "test-client" &&
    arg &&
    (arg === "none" || testClientIdPattern.test(arg)) &&
    rest.length === 0
  ) {
    await updateSettings(({ testClientId: _previous, ...settings }) =>
      arg === "none" ? settings : { ...settings, testClientId: arg },
    );
    process.stdout.write("Alcove test client updated.\n");
    return;
  }
  if (action === "set-owner" && arg && subjectPattern.test(arg) && rest.length === 0) {
    await updateSettings((settings) => ({ ...settings, ownerSubject: arg.toLowerCase() }));
    process.stdout.write("Alcove owner subject updated. Restart the listener.\n");
    return;
  }
  if (action === "refresh-storage-limits" && arg === undefined && rest.length === 0) {
    const storageLimits = measureStorageLimits(stateDir);
    await updateSettings((settings) => ({ ...settings, storageLimits }));
    process.stdout.write(
      `Alcove storage limits updated: ${storageLimits.userBytes} bytes per member, ${storageLimits.globalBytes} bytes shared. Restart the listener.\n`,
    );
    return;
  }
  if (
    action === "cleanup-web-fetch-spills" &&
    (arg === undefined || arg === "--dry-run") &&
    rest.length === 0
  ) {
    const dryRun = arg === "--dry-run";
    const { acquireProtectedStateOwner } = await import("./state-owner.js");
    const owner = await acquireProtectedStateOwner(stateDir);
    if (!owner) {
      throw new MaintenanceRefused("Stop the listener before cleaning web_fetch spill files.");
    }
    try {
      const encryption = requireProtectedStorageEncryption();
      try {
        const stateRoot = await root(stateDir);
        const usersRoot = await root(path.join(stateRoot.rootReal, "users"));
        const { cleanupProtectedWebFetchSpills } = await import("./web-fetch-cleanup.js");
        const result = await cleanupProtectedWebFetchSpills({
          usersRoot,
          assertCurrent: () => owner.assertCurrent(),
          maxBytes: protectedMaxFileBytes,
          encryption,
          dryRun,
        });
        if (dryRun) {
          process.stdout.write(
            result.actions.length > 0
              ? `${result.actions.map(({ kind, path: filePath }) => `${kind} ${filePath}`).join("\n")}\n`
              : "No matching web_fetch spill files or empty directories.\n",
          );
        } else {
          process.stdout.write(
            `Removed ${result.filesRemoved} web_fetch spill files and ${result.directoriesRemoved} empty directories.\n`,
          );
        }
      } finally {
        encryption.dispose();
      }
    } finally {
      owner.release();
    }
    return;
  }
  if (action === "retire-bootstrap" && arg === undefined && rest.length === 0) {
    const { acquireProtectedStateOwner } = await import("./state-owner.js");
    const owner = await acquireProtectedStateOwner(stateDir);
    if (!owner) {
      throw new MaintenanceRefused("Stop the listener before retiring the workspace bootstrap.");
    }
    let retired: boolean;
    try {
      owner.assertCurrent();
      retired = await retireGeneratedBootstrap(path.join(stateDir, "workspace"), () =>
        owner.assertCurrent(),
      );
    } finally {
      owner.release();
    }
    process.stdout.write(
      retired
        ? "Generated workspace BOOTSTRAP.md retired.\n"
        : "No workspace BOOTSTRAP.md to retire.\n",
    );
    return;
  }
  if (action === "archive-residue" && arg === undefined && rest.length === 0) {
    const { acquireProtectedStateOwner } = await import("./state-owner.js");
    const owner = await acquireProtectedStateOwner(stateDir);
    if (!owner) {
      throw new MaintenanceRefused(
        "Protected state is busy; stop the listener or wait for maintenance to finish.",
      );
    }
    try {
      const { inspectConfiguredSqliteTranscriptArchiveResidue } =
        await import("../../src/config/sessions/session-accessor.js");
      const report = await inspectConfiguredSqliteTranscriptArchiveResidue({
        config: protectedOpenClawConfig(stateDir, fileURLToPath(new URL("../..", import.meta.url))),
        env: { ...process.env, OPENCLAW_STATE_DIR: stateDir },
        assertCurrent: () => owner.assertCurrent(),
      });
      owner.assertCurrent();
      process.stdout.write(`${JSON.stringify(report)}\n`);
    } finally {
      owner.release();
    }
    return;
  }
  if (action !== "revoke-profile" || !arg || !/^[a-zA-Z0-9_-]{1,128}$/u.test(arg) || rest.length) {
    throw new Error(
      "Supported commands: init --deploy-json FILE, provision-storage-key, add-subject UUID, set-owner UUID, refresh-storage-limits, cleanup-web-fetch-spills [--dry-run], test-client CLIENT_ID|none, revoke-profile PROFILE_ID, retire-bootstrap, archive-residue, turn-timings.",
    );
  }
  const { acquireProtectedStateOwner } = await import("./state-owner.js");
  const owner = await acquireProtectedStateOwner(stateDir);
  if (!owner) {
    throw new MaintenanceRefused("Stop the listener before revoking a profile.");
  }
  let changed: boolean;
  try {
    const { updateCanonicalUserProfileAccess } =
      await import("../../src/state/user-profile-access.js");
    owner.assertCurrent();
    changed = await updateCanonicalUserProfileAccess(
      { action: "revoke", profileId: arg },
      {
        env: {
          OPENCLAW_STATE_DIR: stateDir,
          OPENCLAW_PROTECTED_STORAGE_KEY_FILE: process.env.OPENCLAW_PROTECTED_STORAGE_KEY_FILE,
        },
      },
    );
  } finally {
    owner.release();
  }
  if (!changed) {
    throw new Error("No matching active Alcove profile");
  }
  process.stdout.write("Alcove profile revoked.\n");
}

void main().catch((error: unknown) => {
  if (error instanceof MaintenanceRefused) {
    process.stderr.write(`${error.message}\n`);
    process.exitCode = 1;
    return;
  }
  process.stderr.write(
    "Alcove maintenance failed. Check the isolated account, config, and command arguments.\n",
  );
  process.exitCode = 1;
});
